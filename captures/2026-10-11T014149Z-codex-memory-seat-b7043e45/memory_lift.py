#!/usr/bin/env python3
"""Independent exact 12-state memory lift of the filled-K4 chain generator."""
import itertools
import json
from fractions import Fraction as F

V=tuple(range(4))
S=[list(itertools.combinations(V,k)) for k in (1,2,3,4)]
O=(0,4,10,14)
def z(n,m): return [[F(0) for _ in range(m)] for _ in range(n)]
def eye(n):
    x=z(n,n)
    for i in range(n): x[i][i]=F(1)
    return x
def tr(a): return [list(v) for v in zip(*a)]
def mul(a,b): return [[sum((a[i][k]*b[k][j] for k in range(len(b))),F(0))
                       for j in range(len(b[0]))] for i in range(len(a))]
def add(a,b,sa=F(1),sb=F(1)):
    return [[sa*x+sb*y for x,y in zip(ra,rb)] for ra,rb in zip(a,b)]
def boundary(a,b):
    x=z(len(a),len(b)); ix={t:i for i,t in enumerate(a)}
    for j,t in enumerate(b):
        for k in range(len(t)): x[ix[t[:k]+t[k+1:]]][j]=F((-1)**k)
    return x
def action(r,simplices):
    x=z(len(simplices),len(simplices)); ix={t:i for i,t in enumerate(simplices)}
    for j,t in enumerate(simplices):
        image=tuple(r[v] for v in t)
        inversions=sum(image[i]>image[k] for i in range(len(image)) for k in range(i+1,len(image)))
        x[ix[tuple(sorted(image))]][j]=F((-1)**inversions)
    return x
def main():
    b1,b2,b3=[boundary(S[k],S[k+1]) for k in range(3)]
    assert mul(b1,b2)==z(4,4) and mul(b2,b3)==z(6,1)
    l1=add(mul(tr(b1),b1),mul(b2,tr(b2)))
    assert l1==add(z(6,6),eye(6),sb=F(4))
    a=z(15,15)
    for k,b in enumerate((b1,b2,b3)):
        for i in range(len(b)):
            for j in range(len(b[0])):
                a[O[k]+i][O[k+1]+j]=-b[i][j]
                a[O[k+1]+j][O[k]+i]=b[i][j]
    assert tr(a)==add(z(15,15),a,sb=F(-1))
    # q=c1, p=q'=B1^T c0-B2 c2. This lift is the unique minimum-norm
    # completion of p among c0,c2, with c3=0 and uniform c0=0.
    lift=z(15,12)
    for i in range(6): lift[4+i][i]=F(1)
    for i in range(4):
        for j in range(6): lift[i][6+j]=b1[i][j]/4
    for i in range(4):
        for j in range(6): lift[10+i][6+j]=-b2[j][i]/4
    metric=z(12,12); gen=z(12,12)
    for i in range(6):
        metric[i][i]=F(1); metric[6+i][6+i]=F(1,4)
        gen[i][6+i]=F(1); gen[6+i][i]=F(-4)
    assert mul(tr(lift),lift)==metric
    assert mul(a,lift)==mul(lift,gen)
    assert add(mul(tr(gen),metric),mul(metric,gen))==z(12,12)
    assert mul(mul(gen,gen),gen)==add(z(12,12),gen,sb=F(-4))
    mq=z(12,12)
    for i in range(6): mq[i][6+i]=F(1,2); mq[6+i][i]=F(-2)
    mh=add(z(12,12),eye(12),sb=F(-1))
    assert mul(mq,mq)==mh
    assert mul(tr(mq),mul(metric,mq))==metric
    inv_q=add(z(12,12),mq,sb=F(-1))
    assert mul(inv_q,mq)==eye(12)
    # The q-only 6-by-6 compression vanishes at a quarter-step, while its
    # memory companion p records the six independent oriented edge probes.
    assert [row[:6] for row in mq[:6]]==z(6,6)
    assert [row[:6] for row in mq[6:]]==add(z(6,6),eye(6),sb=F(-2))
    group=list(itertools.permutations(V)); reps=set()
    for r in group:
        rho=action(r,S[1])
        full=z(15,15)
        for k,simplices in enumerate(S):
            block=action(r,simplices)
            for i in range(len(block)):
                for j in range(len(block)):
                    full[O[k]+i][O[k]+j]=block[i][j]
        rmem=z(12,12)
        for k in (0,6):
            for i in range(6):
                for j in range(6): rmem[k+i][k+j]=rho[i][j]
        assert mul(full,lift)==mul(lift,rmem)
        assert mul(rmem,mq)==mul(mq,rmem)
        # CONDITIONAL observed-frame fixture, not a frame generated by A:
        # observed=rmem*intrinsic, co-moving=intrinsic.
        residual=mul(mul(rmem,mq),inv_q)
        assert residual==rmem
        reps.add(tuple(map(tuple,residual)))
    assert len(reps)==24
    print(json.dumps({"status":"EXACT native memory lift / conditional frame fixture",
      "carrier":"C1 q plus source-derived C1 derivative p, 12-dimensional",
      "lift":"c0=B1 p/4; c1=q; c2=-B2^T p/4; c3=0",
      "evolution":"q'=p; p'=-4q",
      "induced_metric":"diag(I6,I6/4)","quarter_step":"(q,p)->(p/2,-2q)",
      "quarter_step_invertible":True,"q_only_quarter_step":"zero 6x6",
      "full_S4_conditional_frame_cases":len(reps),
      "native_flow_selects_relative_frame":False,
      "physical_promotion":0},indent=2))

if __name__=="__main__": main()
